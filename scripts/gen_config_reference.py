"""Generate ``docs/reference/config.md`` from the composed settings models.

The page lists every setting of core (``untaped.http.*``, ``untaped.ui.*``,
``untaped.skills.*``) and of each first-party plugin's settings model, plus each
plugin's state model. Types, defaults and environment variables come from
the Pydantic models, and each description from the field's
``Field(description=...)``, followed by its :class:`~untaped.sdk._schema.Choices`
names and its bounds when it has them.

Usage::

    uv run python scripts/gen_config_reference.py          # rewrite the page
    uv run python scripts/gen_config_reference.py --check  # exit 1 if stale

``tests/repo/test_docs.py`` fails when the checked-in page is
stale or a setting has no description.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path
from types import UnionType
from typing import TYPE_CHECKING, Annotated, Any, Literal, Union, get_args, get_origin

from packaging.utils import canonicalize_name
from pydantic import BaseModel, HttpUrl, SecretStr
from release import packages

if TYPE_CHECKING:
    from untaped.core.surface._settings import Section
    from untaped.runtime.registry import PluginCandidate
    from untaped.sdk._schema import Choices
    from untaped.sdk.marks import Stability

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = REPO_ROOT / "docs" / "reference" / "config.md"

_HEADER = """\
<!-- Generated by scripts/gen_config_reference.py. Do not edit by hand. -->

# Configuration reference

Every setting `untaped` reads, generated from the settings models. Profile
settings live under `profiles.<name>.<section>` in `~/.untaped/config.yml`;
state lives in `~/.untaped/state.yml` and is written only by the owning
plugin's commands. See [Configuration](../configuration.md) for the file
layout, profiles and precedence.

Set a profile setting with `untaped config set KEY VALUE` (a token:
`untaped auth login SECTION`; how values are parsed is in
[Settings](../configuration.md#settings)). Each profile setting can be
overridden for one process with the environment variable shown.
"""

_FOOTER = """\
## See also

- [Configuration](../configuration.md)
- [Environment variables](./environment.md)
"""


@dataclass(frozen=True)
class Row:
    """One documented setting."""

    key: str
    annotation: Any
    """The leaf type, ``X`` for ``X | None``."""
    default: Any
    description: str | None
    optional: bool = False
    """Whether the setting is ``X | None``."""
    mark: Stability | None = None
    """The setting's own mark, else its plugin's."""


def _type_name(row: Row) -> str:
    name = _annotation_name(row.annotation)
    return f"{name} (optional)" if row.optional else name


def _annotation_name(inner: Any) -> str:
    origin = get_origin(inner)
    if inner is SecretStr:
        return "secret"
    if inner is HttpUrl:
        return "URL"
    if origin is Literal:
        return " \\| ".join(f"`{arg}`" for arg in get_args(inner))
    if origin is Annotated:
        return _annotation_name(get_args(inner)[0])
    if origin in (Union, UnionType):
        return " or ".join(_annotation_name(arg) for arg in get_args(inner))
    if origin is list:
        return "list"
    if origin is dict:
        return "mapping"
    if inner is Path:
        return "path"
    if isinstance(inner, type):
        return {"str": "string", "int": "integer", "float": "number", "bool": "boolean"}.get(
            inner.__name__, inner.__name__
        )
    return str(inner)


def _default_text(value: Any) -> str:
    if value is None:
        return "unset"
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, BaseModel):
        value = value.model_dump()
    if isinstance(value, (list, dict)):
        if not value:
            return "empty"
        return "; ".join(f"`{item}`" for item in value) if isinstance(value, list) else "built-in"
    return f"`{value}`"


def _env_name(key: str) -> str:
    from untaped.runtime.settings import env_var_name  # noqa: PLC0415

    return env_var_name(key.split("."))


def _first_party() -> tuple[PluginCandidate, ...]:
    """The installed candidates of this repository's own distributions."""
    from untaped.runtime.registry import discover_candidates  # noqa: PLC0415

    own = packages(REPO_ROOT)
    return tuple(c for c in discover_candidates() if canonicalize_name(c.distribution) in own)


def collect_sections() -> list[Section]:
    """``(title, prefix, model, is_state, stability, rows)``: core and each first-party plugin.

    ``stability`` is the owning plugin's mark; ``rows`` its typed state rows. Plugins follow in name
    order. Raises :class:`RuntimeError` naming every quarantined first-party
    plugin rather than drop its section.
    """
    from untaped.core.surface._settings import check_quarantine, sections  # noqa: PLC0415
    from untaped.runtime.bootstrap import SHELL_SPEC  # noqa: PLC0415
    from untaped.runtime.registry import compose  # noqa: PLC0415

    result = compose(SHELL_SPEC, _first_party())
    check_quarantine(result)
    return sections(result, extensions=False)


def missing_descriptions() -> list[str]:
    """Settings keys whose field has no ``description``."""
    return [row.key for row in _all_rows() if not row.description]


def _all_rows() -> list[Row]:
    rows: list[Row] = []
    for section in collect_sections():
        rows.extend(_section_rows(section))
    return rows


def _section_rows(section: Section) -> list[Row]:
    from untaped.core.surface._settings import setting_leaves  # noqa: PLC0415

    return [
        Row(
            leaf.key,
            leaf.annotation,
            leaf.default,
            _with_bounds(
                _with_choices(
                    leaf.description,
                    leaf.choices,
                    mapping=leaf.annotation is dict or get_origin(leaf.annotation) is dict,
                ),
                leaf.bounds,
            ),
            optional=leaf.optional,
            mark=leaf.mark,
        )
        for leaf in setting_leaves(section)
    ]


def _with_choices(description: str | None, choices: Choices | None, *, mapping: bool) -> str | None:
    """``description``, then the names a :class:`Choices` field accepts (a mapping's keys)."""
    if description is None or choices is None:
        return description
    lead = "Names" if mapping else "One of"
    names = ", ".join(f"`{name}`" for name in choices.names())
    return f"{description} {lead}: {names}."


def _with_bounds(description: str | None, bounds: str | None) -> str | None:
    """``description``, then the field's bounds (``Above 0.``), as the setup screen shows them."""
    if description is None or bounds is None:
        return description
    return f"{description} {bounds}"


def _description(row: Row) -> str:
    """The description cell: the text, then the sentence for a marked setting."""
    from untaped.sdk.marks import Deprecated, removal_text, replacement_text  # noqa: PLC0415
    from untaped.sdk.words import EXPERIMENTAL_LINE, deprecated_line  # noqa: PLC0415

    if row.mark is None:
        return str(row.description)
    if isinstance(row.mark, Deprecated):
        owner = {c.name: c.distribution for c in _first_party()}.get(row.key.partition(".")[0])
        removal = removal_text(row.mark.removed_in, owner)
        line = deprecated_line(replacement_text(row.mark, None), removal)
    else:
        line = EXPERIMENTAL_LINE
    return f"{row.description} {line}"


def _renamed_table() -> list[str]:
    """The Renamed settings table: every declared rename, in section order."""
    from untaped.sdk.health.deprecated_keys import key_mappings  # noqa: PLC0415

    rows: list[str] = []
    for _, prefix, model, is_state, _, _ in collect_sections():
        if is_state:
            continue
        for section, section_model in {prefix: model}.items():
            mappings = key_mappings(section_model)
            for old, new in sorted(mappings.migratable.items()):
                kind = "retired" if old in mappings.retired else "renamed"
                key = f"{section}.{old}"
                rows.append(f"| `{key}` | `{_env_name(key)}` | `{section}.{new}` | {kind} |")
            for old, deleted in sorted(mappings.deleted.items()):
                key = f"{section}.{old}"
                reason = deleted.reason()
                status = reason if reason.startswith("deleted") else f"deleted: {reason}"
                rows.append(f"| `{key}` | `{_env_name(key)}` | none | {status} |")
    if not rows:
        return []
    return [
        "## Renamed settings\n",
        "A renamed key is still read with a warning; a retired one is no longer read; a "
        "deleted one is no longer read and `config migrate` removes it. See "
        "[Renamed settings](../configuration.md#renamed-settings).\n",
        "| Old key | Old environment variable | New key | Status |\n|---|---|---|---|",
        *rows,
        "",
    ]


def render() -> str:
    """Return the full Markdown page."""
    parts = [_HEADER]
    for section in collect_sections():
        rows = _section_rows(section)
        if not rows:
            continue
        parts.append(f"## {section.title}\n")
        if section.is_state:
            parts.append("| Key | Type | Description |\n|---|---|---|")
            for row in rows:
                parts.append(f"| `{row.key}` | {_type_name(row)} | {_description(row)} |")
        else:
            parts.append(
                "| Key | Type | Default | Environment | Description |\n|---|---|---|---|---|"
            )
            for row in rows:
                parts.append(
                    f"| `{row.key}` | {_type_name(row)} | {_default_text(row.default)} "
                    f"| `{_env_name(row.key)}` | {_description(row)} |"
                )
        parts.append("")
    parts.extend(_renamed_table())
    parts.append(_FOOTER)
    return "\n".join(parts)


def main(argv: list[str]) -> int:
    """Write the page, or with ``--check`` report whether it is current."""
    page = render()
    if "--check" in argv:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != page:
            print(f"{OUTPUT} is stale; run: uv run python scripts/gen_config_reference.py")
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(page, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
