jobs_app = create_app(name="jobs", help="Inspect, cancel and relaunch AWX jobs.")

# Default ``table`` columns (raw AWX field names); json, yaml and pipe keep whole records.
_JOB_LIST_COLUMNS = ("id", "name", "status", "launch_type", "started", "elapsed")
_RAW_JOB_LIST_COLUMNS = ("id", "name", "status")
"""``--format raw`` keeps its tab-separated projection."""
_JOB_GET_COLUMNS = ("id", "name", "status", "started", "finished", "elapsed", "job_explanation")
_JOB_WAIT_COLUMNS = ("id", "name", "status", "finished_at", "elapsed")


@jobs_app.command(name="list")
def jobs_list(
    *,
    status: Annotated[
        str | None,
        Parameter(name="--status", help="Filter by AWX status (e.g. running, successful, failed)."),
    ] = None,
    filter_: Annotated[
        list[str] | None,
        Parameter(
            name="--filter",
            help="Server-side filter, KEY=VALUE (repeatable). Forwarded verbatim.",
            consume_multiple=False,
            negative="",
        ),
    ] = None,
    limit: LimitOption = 20,
    kind: JobKindOption = "job",
    template: Annotated[
        str | None,
        Parameter(
            name="--template",
            help=(
                "Only runs of this template (project or inventory source for updates): "
                "a name, or digits for an AWX id."
            ),
        ),
    ] = None,
    fmt: FormatOption = "table",
    columns: ColumnsOption = None,
) -> None:
    """List recent AWX jobs (newest first).

    --template takes digits as an id; match a numeric name with `--filter
    job_template__name=123`. Tables show a summary; json and yaml carry the
    whole record.
    """
    filters = parse_kv_pairs(filter_, flag="--filter")
    if status:
        filters["status"] = status
    if template is not None:
        field = JOB_ROUTES[kind].template_field
        if field is None:
            raise_usage(f"--template does not apply to {kind} executions")
        filters[field if template.isdigit() else f"{field}__name"] = template
    with report_errors(), open_context() as ctx, ctx.diag.progress("Loading jobs"):
        records = list(ctx.jobs.list(kind=kind, params=filters, limit=limit))
    emit(
        [JobRecord.model_validate(record) for record in records],
        fmt=fmt,
        columns=columns or (list(_RAW_JOB_LIST_COLUMNS) if fmt == "raw" else None),
        table_columns=_JOB_LIST_COLUMNS,
        empty="No jobs found. Try a different --status or --filter.",
    )


@jobs_app.command(name="get")
def jobs_get(
    job_ids: JobIdsArgument = None,
    /,
    *,
    stdin: JobsStdinOption = False,
    kind: JobKindOption = "job",
    fmt: FormatOption = "table",
    columns: ColumnsOption = None,
) -> None:
    """Fetch one or more jobs by id."""
    # Hoisted so they're bound even if ``report_errors`` swallows the
    # body — keeps the post-``with`` exit-code dispatch safe.
    records: list[JobRecord] = []
    any_failed = False
    with report_errors(), open_context() as ctx:
        ids, kinds = _job_targets(job_ids, stdin=stdin)
        records, any_failed = resolve_each(
            ids,
            lambda n: JobRecord.model_validate(
                ctx.jobs.get(kind=kinds.get(n, kind), job_id=_as_job_id(n))
            ),
        )
    if records:
        emit(records, fmt=fmt, columns=columns, table_columns=_JOB_GET_COLUMNS)
    finish(any_failed)


@jobs_app.command(name="events")
def jobs_events(
    job_ids: JobIdsArgument = None,
    /,
    *,
    stdin: JobsStdinOption = False,
    follow: Annotated[
        bool,
        Parameter(name="--follow", negative="", help="Tail events live until terminal."),
    ] = False,
    from_counter: Annotated[
        int,
        Parameter(name="--from-counter", help="Skip events with counter <= this value."),
    ] = 0,
    filter_: Annotated[
        list[str] | None,
        Parameter(
            name="--filter",
            help="Server-side AWX filter, KEY=VALUE (repeatable). E.g. event=runner_on_failed.",
            consume_multiple=False,
            negative="",
        ),
    ] = None,
    kind: JobKindOption = "job",
    fmt: FormatOption = "table",
    columns: ColumnsOption = None,
) -> None:
    """Stream the structured per-task event log for one or more jobs.

    Without `--follow` this drains each job's event log and exits; with
    `--follow` it polls AWX every 2s until each job is terminal. Filters reach
    AWX directly so you can scope server-side, e.g. `--filter
    event=runner_on_failed --filter host=web-01`. A workflow job has no
    events (use `jobs wait`).

    Multiple ids drain serially with a `[<id>]` stderr breadcrumb between
    jobs. Without `--follow`, `--format json`/`yaml` print one array holding
    every job's events; each row names its `job`. With `--follow`, json
    streams one object per line (NDJSON). `--columns ?` lists the columns
    without following.
    """
    filters = parse_kv_pairs(filter_, flag="--filter")
    cols = columns or (list(_RAW_EVENT_COLUMNS) if fmt == "raw" else None)
    follow = follow and cols != ["?"]
    one_document = _is_one_document(fmt, follow=follow)
    rows: list[JobEventRow] = []
    # Hoisted so post-``with`` exit dispatch is safe regardless of body outcome.
    any_failed = False
    with report_errors(), open_context() as ctx:
        ids, kinds = _job_targets(job_ids, stdin=stdin)
        show_breadcrumb = len(ids) > 1

        def _events_for_id(n: str) -> None:
            job_id = _as_job_id(n)
            job_kind = kinds.get(n, kind)
            record = ctx.jobs.get(kind=job_kind, job_id=job_id)
            job = Job.model_validate({**record, "kind": job_kind})
            if show_breadcrumb:
                ctx.diag.info(f"[{job_id}]", unmuted=True)
            events = ctx.monitor.stream_events(
                job, from_counter=from_counter, params=filters, follow=follow
            )
            if one_document:
                rows.extend(_event_row(ev, job_id) for ev in events)
                return
            _emit_events(events, job_id=job_id, fmt=fmt, cols=cols, follow=follow, ui=ctx.ui())

        drained, any_failed = resolve_each(ids, _events_for_id)
        if one_document and drained:
            # Named, so ``-c ?`` lists the defaults on a job with no events yet.
            emit(rows, fmt=fmt, columns=cols, table_columns=JobEventRow.table_columns)
    finish(any_failed)


def _is_one_document(fmt: OutputFormat, *, follow: bool) -> bool:
    """Whether several jobs' rows merge into one json/yaml document.

    json and yaml print a single document per invocation; ``--follow``
    streams instead (json as NDJSON), and the other formats are line or
    table oriented, so they keep emitting per job.
    """
    return not follow and fmt in ("json", "yaml")


_RAW_EVENT_COLUMNS = ("counter", "event", "host_name", "task")
"""``--format raw`` keeps its tab-separated projection."""


def _event_row(ev: JobEvent, job_id: int) -> JobEventRow:
    return JobEventRow(job=job_id, **ev.model_dump())


def _emit_events(
    events: Iterable[JobEvent],
    *,
    job_id: int,
    fmt: OutputFormat,
    cols: list[str] | None,
    follow: bool,
    ui: UiContext,
) -> None:
    """Lifted out of the per-id closure so multi-id callers reuse
    the single-id rendering verbatim — no behavioural drift between
    batch and single modes."""
    if not follow:
        # One-shot drain: collect everything then format as a single
        # table / json document so columns line up and yaml stays a
        # well-formed list.
        emit(
            [_event_row(ev, job_id) for ev in events],
            fmt=fmt,
            columns=cols,
            table_columns=JobEventRow.table_columns,
        )
        return
    if fmt == "table":
        # Table mode under --follow renders each event as a colored
        # human-readable line (PLAY [..] / TASK [..] / "  ok: host"),
        # similar to the AWX UI's Output tab. ``ui.styled`` emits ANSI
        # on a real terminal and plain text when piped or redirected.
        for ev in events:
            ui.styled(render_event_text(ev))
        return
    # Other formats (json/yaml/raw) stream one structured row at a
    # time — useful for ``--follow | jq``-style pipelines.
    # JSON streams as NDJSON (one bare object per line, no enclosing
    # array brackets) to match ``kubectl get -w -o json`` and so
    # ``jq`` can ingest it directly without ``jq -s '.[]'``.
    if fmt == "json":
        for ev in events:
            emit(_event_row(ev, job_id), fmt="json", columns=cols)
        return
    for ev in events:
        emit([_event_row(ev, job_id)], fmt=fmt, columns=cols)


def _emit_log_lines(
    lines: Iterable[str],
    *,
    job_id: int,
    fmt: OutputFormat,
    cols: list[str] | None,
    follow: bool,
) -> None:
    """Render the stdout of a job. Sibling of :func:`_emit_events`.

    ``cols=None`` means the whole ``{job, line}`` row, less ``job`` in a table.
    """
    if not follow:
        emit(
            [_log_row(line, job_id) for line in lines],
            fmt=fmt,
            columns=cols,
            table_columns=JobLogLine.table_columns,
        )
        return
    # JSON streams as NDJSON (one bare object per line, no enclosing
    # array brackets) to match ``jobs events --follow --format json``
    # and so ``jq`` can ingest it directly without ``jq -s '.[]'``.
    if fmt == "json":
        for line in lines:
            emit(_log_row(line, job_id), fmt="json", columns=cols)
        return
    if fmt == "raw":
        # Skip the no-op row-rendering round-trip — raw lines are
        # already the final shape, and the per-line wrap is the hot path
        # on a 100k-line follow stream. ``cols`` is ignored here: log
        # rows are single-field (``line``), so any projection is either
        # the identity or a path miss; the only meaningful value is
        # ``--columns line``, which is what users pass.
        for line in lines:
            echo(line)
        return
    # No Rich table branch (unlike ``_emit_events``): log lines are
    # unstructured text, so ``--format table --follow`` falls through
    # to per-line row rendering like yaml does. Table-per-line is
    # silly but the cost is on the user who asked for it.
    for line in lines:
        emit([_log_row(line, job_id)], fmt=fmt, columns=cols)


def _log_row(line: str, job_id: int) -> JobLogLine:
    return JobLogLine(job=job_id, line=line)


@jobs_app.command(name="logs")
def jobs_logs(
    job_ids: JobIdsArgument = None,
    /,
    *,
    stdin: JobsStdinOption = False,
    follow: Annotated[
        bool,
        Parameter(name="--follow", negative="", help="Tail until terminal."),
    ] = False,
    tail: Annotated[
        int | None,
        Parameter(
            name="--tail",
            help="Show only the last N historical lines before following.",
            validator=Number(gte=0),
        ),
    ] = None,
    grep: Annotated[
        str | None,
        Parameter(name="--grep", help="Client-side regex; only matching lines are printed."),
    ] = None,
    ignore_case: Annotated[
        bool,
        Parameter(name=["--ignore-case", "-i"], negative="", help="Case-insensitive --grep."),
    ] = False,
    kind: JobKindOption = "job",
    fmt: FormatOption = "raw",
    columns: ColumnsOption = None,
) -> None:
    """Print the stdout of one or more jobs. Supports follow / tail / grep.

    It downloads the full stdout. With --follow it reads only new events on
    each poll (colours removed); `--tail N --follow` starts from the newest
    events. Project and inventory updates have logs (--kind); a workflow job
    has none (use `jobs wait`).

    Multiple ids drain serially with a `[<id>]` stderr breadcrumb between
    jobs. Without --follow, `--format json`/`yaml` print one array holding
    every job's lines; each row names its `job`. `--columns ?` lists the
    columns without following.
    """
    if grep is not None:
        # Compile here so an invalid regex fails fast as a clean
        # usage error rather than
        # leaking a ``re.error`` traceback through ``report_errors`` later.
        try:
            re.compile(grep, re.IGNORECASE if ignore_case else 0)
        except re.error as exc:
            raise_usage(f"--grep {grep!r} is not a valid regex: {exc}")
    # Hoisted so post-``with`` exit dispatch is safe regardless of body outcome.
    any_failed = False
    with report_errors(), open_context() as ctx:
        ids, kinds = _job_targets(job_ids, stdin=stdin)
        show_breadcrumb = len(ids) > 1
        # Log rows are ``{job, line}``; the line-oriented formats show the line.
        cols = columns or (["line"] if fmt == "raw" else None)
        follow = follow and cols != ["?"]
        one_document = _is_one_document(fmt, follow=follow)
        rows: list[JobLogLine] = []

        def _logs_for_id(n: str) -> None:
            job_id = _as_job_id(n)
            job_kind = kinds.get(n, kind)
            record = ctx.jobs.get(kind=job_kind, job_id=job_id)
            job = Job.model_validate({**record, "kind": job_kind})
            if show_breadcrumb:
                ctx.diag.info(f"[{job_id}]", unmuted=True)
            lines = TailJobLogs(ctx.monitor)(
                job, follow=follow, grep=grep, ignore_case=ignore_case, tail=tail
            )
            if one_document:
                rows.extend(_log_row(line, job_id) for line in lines)
                return
            _emit_log_lines(lines, job_id=job_id, fmt=fmt, cols=cols, follow=follow)

        drained, any_failed = resolve_each(ids, _logs_for_id)
        if one_document and drained:
            # Named, so ``-c ?`` lists the defaults on a job with no lines yet.
            emit(rows, fmt=fmt, columns=cols, table_columns=JobLogLine.table_columns)
    finish(any_failed)


@jobs_app.command(name="wait")
def jobs_wait(
    job_ids: JobIdsArgument = None,
    /,
    *,
    stdin: JobsStdinOption = False,
    timeout: Annotated[
        float | None,
        Parameter(name="--timeout", help="Seconds to wait before giving up (applies per id)."),
    ] = None,
    kind: JobKindOption = "job",
    fmt: FormatOption = "table",
    columns: ColumnsOption = None,
) -> None:
    """Block until each named job reaches a terminal state.

    Exits non-zero on unsuccessful terminal states, timeout, or resolution failure —
    same contract as ``awx test``. Multiple ids drain serially; the
    ``--timeout`` budget applies per id.
    """
    # Hoisted so post-``with`` exit dispatch is safe regardless of body outcome.
    records: list[JobRecord] = []
    any_failed = False
    timed_out: list[int] = []
    with report_errors(), open_context() as ctx:
        ids, kinds = _job_targets(job_ids, stdin=stdin)

        def _wait_one(n: str) -> JobRecord:
            job_id = _as_job_id(n)
            job_kind = kinds.get(n, kind)
            record = ctx.jobs.get(kind=job_kind, job_id=job_id)
            job = Job.model_validate({**record, "kind": job_kind})
            final = WatchJob(ctx.repo)(job, timeout=timeout)
            if not final.is_terminal:
                timed_out.append(job_id)
            return JobRecord.model_validate(final.model_dump(mode="json"))

        records, any_failed = resolve_each(ids, _wait_one)
    if records:
        emit(records, fmt=fmt, columns=columns, table_columns=_JOB_WAIT_COLUMNS)
    for job_id in timed_out:
        ctx.diag.warning(f"job {job_id}: timed out before reaching a terminal state")
    finish(any_failed or bool(timed_out) or any(r.status != "successful" for r in records))


